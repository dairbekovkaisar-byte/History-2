function localOralScore(text){
  const words=text.split(/\s+/).filter(Boolean);
  const relevant=relevantOralTopic(text);
  const corpus=(relevant.facts.join(' ')+' '+relevant.dates.join(' ')+' '+relevant.people.join(' ')+' '+relevant.terms.join(' ')).toLowerCase();
  const keys=[...new Set(corpus.match(/[\p{L}][\p{L}\-]{4,}/gu)||[])].slice(0,45);
  const lower=text.toLowerCase();
  const hit=keys.filter(k=>lower.includes(k)).length;
  const knowledge=Math.min(40,Math.round(12+hit*2.6));
  const analysisWords=/(причин|потому|следств|значен|итог|влияни|себеп|салдар|маңыз|нәтиже|әсер|сондықтан|өйткені|because|cause|consequence|significance|result|impact|therefore|due to)/i.test(text);
  const structureWords=/(во-первых|во-вторых|таким образом|итог|қорытынды|біріншіден|екіншіден|сондықтан|нәтижесінде|firstly|secondly|therefore|in conclusion|as a result|overall)/i.test(text);
  const analysis=Math.min(30,Math.round((analysisWords?18:10)+(words.length>80?8:words.length>45?4:0)));
  const structure=Math.min(20,Math.round((words.length>60?12:8)+(structureWords?6:2)));
  const language=Math.min(10,Math.round(words.length>35?8:6));
  return {score:knowledge+analysis+structure+language,knowledge,analysis,structure,language,feedback:t().improveText,strengths:[],improvements:[t().improveText]};
}

function renderOralResult(result, source='local'){
  const limits=[40,30,20,10];
  const values=[result.knowledge,result.analysis,result.structure,result.language].map((value,i)=>Math.max(0,Math.min(limits[i],Number(value)||0)));
  const score=values.reduce((sum,value)=>sum+value,0);
  const strengths=Array.isArray(result.strengths)?result.strengths.slice(0,4):[];
  const improvements=Array.isArray(result.improvements)?result.improvements.slice(0,4):[];
  const feedback=String(result.feedback||'').trim();
  state.oral.push({score,date:Date.now(),q:oralQuestion,source}); save();
  const rows=t().rubricNames.map((name,i)=>[name,values[i],limits[i]]);
  document.getElementById('oralFeedback').innerHTML=`<div class="card oral-result" style="box-shadow:none"><div class="eyebrow">${source==='gemini'?t().aiFeedback:t().result}</div><h2>${score} / 100</h2>${rows.map(x=>`<div class="score-row"><div><strong>${x[0]}</strong><div class="progress"><span style="width:${x[1]/x[2]*100}%"></span></div></div><strong>${x[1]}/${x[2]}</strong></div>`).join('')}${feedback?`<div class="callout"><strong>${t().aiFeedback}</strong><br>${escapeHtml(feedback)}</div>`:''}${strengths.length?`<div class="ai-list"><strong>${t().aiStrengths}</strong><ul>${strengths.map(item=>`<li>${escapeHtml(item)}</li>`).join('')}</ul></div>`:''}${improvements.length?`<div class="ai-list"><strong>${t().aiImprovements}</strong><ul>${improvements.map(item=>`<li>${escapeHtml(item)}</li>`).join('')}</ul></div>`:''}</div>`;
}

