function readiness(){
  const done = state.done.length / topics().length * 55;
  const prac = Object.values(state.practice).map(Number).filter(Number.isFinite);
  const p = prac.length ? prac.reduce((a,b)=>a+b,0)/prac.length : 0;
  const oral = state.oral.length ? state.oral.reduce((a,b)=>a+(Number(b.score)||0),0)/state.oral.length : 0;
  return Math.round(Math.min(100, done + p*.25 + oral*.2));
}
