function distractors(topicId, field){
  const values=[];
  for(const topic of topics()){
    if(topic.id===topicId) continue;
    const source=topic[field];
    if(Array.isArray(source) && source.length) values.push(source[0]);
    else if(typeof source === 'string' && source) values.push(source);
  }
  return shuffle([...new Set(values)]).slice(0,3);
}
function buildPracticeBankForTopic(topicId){
  const staticBank=weeklyPracticeBanks[topicId];
  if(staticBank && staticBank.length){
    return staticBank.map(item=>({topic:topicId,q:item.q,correct:item.correct,options:item.options,exp:item.exp}));
  }
  const topic=topics().find(x=>x.id===topicId) || topics()[0];
  const items=[];
  const add=(q,correct,field,exp=topic.answer)=>{
    const options=[correct,...distractors(topic.id,field)].slice(0,4);
    while(options.length<4) options.push(`${t().questionNumber} ${options.length+1}`);
    items.push({topic:topic.id,q,correct,options,exp});
  };
  add(interpolate(t().qFact,{title:topic.title}), topic.facts[0], 'facts', t().answerWhy);
  add(interpolate(t().qDate,{title:topic.title}), topic.dates[0], 'dates', t().answerWhy);
  add(interpolate(t().qPeople,{title:topic.title}), topic.people[0], 'people', t().answerWhy);
  add(interpolate(t().qTerm,{title:topic.title}), topic.terms[0], 'terms', t().answerWhy);
  add(interpolate(t().qMust,{title:topic.title}), topic.must[0], 'must', t().answerWhy);
  const answerOptions=[topic.answer,...distractors(topic.id,'answer')];
  items.push({topic:topic.id,q:topic.question,correct:topic.answer,options:answerOptions,exp:topic.answer});
  return items;
}
function prepareQuestion(q){
  const opts=shuffle([...new Set(q.options)]);
  if(!opts.includes(q.correct)) opts.unshift(q.correct);
  const limited=shuffle(opts).slice(0,4);
  if(!limited.includes(q.correct)) limited[Math.floor(Math.random()*limited.length)] = q.correct;
  return {...q,opts:limited,a:limited.indexOf(q.correct)};
}
