window.scoreOralWithGemini = async () => {
  const answer=document.getElementById('oralAnswer')?.value.trim()||'';
  if(!answer){ toast(t().writeFirst); return; }
  const feedback=document.getElementById('oralFeedback');
  const button=[...document.querySelectorAll('button')].find(item=>item.textContent===t().evaluateGemini);
  if(button){ button.disabled=true; button.textContent=t().aiThinking; }
  if(feedback) feedback.innerHTML=`<div class="feedback">${t().aiThinking}</div>`;
  const topic=relevantOralTopic(answer);
  try{
    const response=await fetch('/api/evaluate',{
      method:'POST',
      headers:{'Content-Type':'application/json'},
      body:JSON.stringify({question:oralQuestion,answer,topic:{title:topic.title,period:topic.period,facts:topic.facts,dates:topic.dates,people:topic.people,terms:topic.terms}})
    });
    const contentType=response.headers.get('content-type')||'';
    if(!contentType.includes('application/json')) throw new Error(t().serverError);
    const payload=await response.json();
    if(!response.ok) throw new Error(payload.error||`API ${response.status}`);
    const result=payload.result;
    renderOralResult(result,'gemini');
  }catch(error){
    const rawMessage=String(error?.message||'');
    const message=/expected pattern|failed to fetch|networkerror|load failed/i.test(rawMessage)?t().serverError:rawMessage;
    if(feedback) feedback.innerHTML=`<div class="feedback"><strong>${t().aiError}</strong><br><small>${escapeHtml(message||'API error')}</small></div>`;
  }finally{
    if(button){ button.disabled=false; button.textContent=t().evaluateGemini; }
  }
};

